export function gerarMedicoes(
	progressoPorMes: Record<string, number>,
): MedDef[] {
	const resultado: MedDef[] = [];
	const meses = Object.entries(progressoPorMes).sort(([a], [b]) =>
		a.localeCompare(b),
	);

	for (const [mes, progressoGeral] of meses) {
		for (const item of ITENS_COM_MEDICAO) {
			let pctItem: number;
			if (item.idx.startsWith("1.")) {
				pctItem = Math.min(1, progressoGeral + 0.25);
			} else if (item.idx.startsWith("2.")) {
				pctItem = Math.max(0, progressoGeral - 0.05);
			} else if (item.idx.startsWith("3.")) {
				pctItem = Math.max(0, progressoGeral - 0.25);
			} else if (item.idx.startsWith("4.")) {
				pctItem = Math.max(0, progressoGeral - 0.45);
			} else if (item.idx.startsWith("5.")) {
				pctItem = Math.max(0, progressoGeral - 0.55);
			} else if (item.idx.startsWith("6.")) {
				pctItem = Math.max(0, progressoGeral - 0.7);
			} else if (item.idx.startsWith("7.")) {
				pctItem = Math.max(0, progressoGeral - 0.8);
			} else {
				pctItem = progressoGeral;
			}
			pctItem = Math.round(pctItem * 100) / 100;
			if (pctItem <= 0) continue;

			const qtyBase = item.qtyBase;
			const qtyAcum =
				qtyBase === 1 ? null : Math.round(qtyBase * pctItem * 100) / 100;

			const dataMedicao = dt(`${mes}-15`);
			const nomeMes = dataMedicao.toLocaleDateString("pt-BR", {
				month: "long",
			});

			resultado.push({
				idx: item.idx,
				date: mes,
				pct: pctItem,
				qty: qtyAcum,
				note: `Medicao de ${nomeMes}/2026`,
			});
		}
	}

	return resultado;
}
